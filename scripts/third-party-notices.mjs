#!/usr/bin/env node
/**
 * Builds public/THIRD-PARTY-NOTICES.txt: the license of every third-party package whose
 * code or assets ship in dist/. Living in public/, it is copied into dist/ by Vite and
 * published next to the app (/draw/THIRD-PARTY-NOTICES.txt), as the MIT license asks for
 * every copy of the software; no in-app link is needed.
 *
 * Shipped packages come from two sources:
 * - the runtime `dependencies` of package.json (Bootstrap CSS and Dialog JS, Bootstrap
 *   Icons SVGs), each listed in SHIPPED with what ships, so a new dependency must be
 *   described here before the build passes;
 * - code the toolchain injects, detected in dist/: Workbox modules in the service worker
 *   (their `workbox:<module>:<version>` markers) and Vite's module preload helper.
 *
 * Usage (after `vite build`):
 *   node scripts/third-party-notices.mjs          regenerate the file (rebuild to ship it)
 *   node scripts/third-party-notices.mjs --check  fail if it is out of date (build, CI)
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const DIST = join(ROOT, 'dist');
const OUTPUT = 'THIRD-PARTY-NOTICES.txt';

/** Runtime dependencies and what of them ships. */
const SHIPPED = {
  bootstrap: 'CSS (compiled from Sass, used modules only) and the Dialog JavaScript component',
  'bootstrap-icons': 'SVG icons (only those used, inlined in the CSS)',
};

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

function packageInfo(name, usage) {
  const dir = join(ROOT, 'node_modules', name);
  const pkg = readJson(join(dir, 'package.json'));
  const licenseFile = readdirSync(dir).find((file) => /^licen[cs]e(\.(md|txt))?$/i.test(file));
  if (!licenseFile) throw new Error(`${name}: no LICENSE file in node_modules`);
  const homepage =
    pkg.homepage ?? (typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url);
  return {
    name,
    version: pkg.version,
    license: pkg.license,
    homepage,
    usage,
    // Vite appends the licenses of its own bundled dependencies (build tooling that never
    // ships): only its core license applies to the injected helper.
    text: readFileSync(join(dir, licenseFile), 'utf8')
      .split(/^# Licenses of bundled dependencies/m)[0]
      .replace(/^# Vite core license\s*/m, '')
      .trim(),
  };
}

function shippedPackages() {
  const dependencies = Object.keys(readJson(join(ROOT, 'package.json')).dependencies ?? {});
  const undescribed = dependencies.filter((name) => !(name in SHIPPED));
  if (undescribed.length > 0) {
    throw new Error(
      `Describe what ships of ${undescribed.join(', ')} in SHIPPED (scripts/third-party-notices.mjs)`,
    );
  }
  const packages = dependencies.map((name) => packageInfo(name, SHIPPED[name]));

  if (!existsSync(DIST)) throw new Error('dist/ is missing: run `vite build` first');
  const scripts = readdirSync(DIST, { recursive: true })
    .filter((file) => String(file).endsWith('.js'))
    .map((file) => readFileSync(join(DIST, String(file)), 'utf8'))
    .join('\n');

  const workbox = [...new Set([...scripts.matchAll(/workbox:([a-z-]+):/g)].map((m) => m[1]))];
  for (const module of workbox.sort()) {
    packages.push(packageInfo(`workbox-${module}`, 'service worker runtime (offline cache)'));
  }
  if (scripts.includes('modulepreload')) {
    packages.push(packageInfo('vite', 'module preload helper injected in the bundle'));
  }
  // Code-unit order, not localeCompare: the --check output must not depend on the locale.
  return packages.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
}

function render(packages) {
  const rule = '-'.repeat(78);
  const lines = [
    'Carnet magique (Magic Sketchbook): third-party notices',
    '',
    'The published app includes the following third-party software.',
    'Generated by scripts/third-party-notices.mjs; do not edit by hand.',
    '',
  ];
  // Packages sharing the same license text (Workbox modules) print it once.
  const groups = new Map();
  for (const pkg of packages) {
    const group = groups.get(pkg.text) ?? [];
    group.push(pkg);
    groups.set(pkg.text, group);
  }
  for (const [text, group] of groups) {
    lines.push(rule);
    for (const pkg of group) {
      lines.push(`${pkg.name} ${pkg.version} (${pkg.license})`);
      lines.push(`  ${pkg.usage}`);
      if (pkg.homepage) lines.push(`  ${pkg.homepage.replace(/^git\+/, '')}`);
    }
    lines.push('', text, '');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

const content = render(shippedPackages());
const target = join(ROOT, 'public', OUTPUT);

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== content) {
    console.error(`${OUTPUT} is out of date: run \`npm run notices\` and commit it.`);
    process.exit(1);
  }
} else {
  writeFileSync(target, content);
  console.log(`Wrote ${OUTPUT}`);
}
